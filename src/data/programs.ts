// Program landing pages (/programy/<slug>/), one per audience. Texts are condensed from the
// club's old site (svitbox.com.ua); claims that may be outdated are marked [уточнити].
// `groups` are schedule group ids (src/data/schedule.ts), `prices` the price track to show.

// SEO layer: texts, headings and meta from the old site page that already ranks in Google.
// When present, the landing keeps the old URL (path), title, description, H1/H2/H3 and body text.
export interface ProgramSeo {
  title: string;
  description: string;
  h1: string;
  imgAlt: string;
  lead: string;
  intro: { h2: string; text: string[] };
  more?: { h3: string; text: string[] };     // second heading block under the intro
  safety?: { h3?: string; text: string[] };  // replaces the short answer in the fear block
  club?: { h2: string; text: string[] };
  advantages?: { h2: string; items: string[] };
  closing?: string;
}

export interface Program {
  slug: string;
  path?: string;           // old site URL to keep (e.g. 'boxing_kids/'); default programy/<slug>/
  seo?: ProgramSeo;
  signup: string;          // option preselected in the sign-up form
  name: string;            // page title / list name
  short: string;           // one line for lists (home, overview)
  kicker: string;          // who it is for
  img: string;
  pos?: string;            // object-position of the hero photo
  age: string;
  when: string;            // short schedule summary
  from: string;            // price from
  lead: string;
  benefits: { t: string; d: string }[];
  fear: { q: string; a: string };
  rounds: { t: string; d: string }[];   // how a training goes
  groups: string[];
  prices: 'box' | 'fit' | null;
  note?: string;           // extra line under schedule
  faq: { q: string; a: string }[];
}

